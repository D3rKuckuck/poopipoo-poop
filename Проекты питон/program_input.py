# int, float, str, bool
a = input("Введи что-нибудь: ")
print(a)
print(type(a))
b = int(input("Введи что-нибудь: "))
print(b, type(b))
b = float(input("Введи что-нибудь: "))
print(b, type(b))
c = 2
print("Число "+str(c))
# int() - Функция конвертации в целое число
# float() - Функция конвертации в число с плавающей точкой
# str() - Функция конвертации в строку
# bool() - Функция конвертации в логическое значение